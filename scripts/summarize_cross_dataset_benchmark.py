"""Build paper-ready comparison tables from completed cross-dataset runs."""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path


FREQ_PRET_RESULTS = {
    ("cifar100", "sig", "Freq-Pret beta=0.1"): (0.69, 0.66, 0.11),
    ("cifar100", "sig", "Freq-Pret beta=1"): (0.60, 0.25, 0.13),
    ("cifar100", "issba", "Freq-Pret beta=0.1"): (0.67, 0.64, 0.17),
    ("cifar100", "issba", "Freq-Pret beta=1"): (0.62, 0.16, 0.32),
    ("cifar100", "blended", "Freq-Pret beta=0.1"): (0.67, 0.93, 0.04),
    ("cifar100", "blended", "Freq-Pret beta=1"): (0.57, 0.00, 0.57),
    ("tinyimagenet", "sig", "Freq-Pret beta=0.1"): (0.53, 0.80, 0.06),
    ("tinyimagenet", "sig", "Freq-Pret beta=1"): (0.38, 0.13, 0.07),
    ("tinyimagenet", "issba", "Freq-Pret beta=0.1"): (0.53, 0.95, 0.02),
    ("tinyimagenet", "issba", "Freq-Pret beta=1"): (0.44, 0.25, 0.18),
    ("tinyimagenet", "blended", "Freq-Pret beta=0.1"): (0.52, 0.98, 0.01),
    ("tinyimagenet", "blended", "Freq-Pret beta=1"): (0.41, 0.06, 0.24),
}


def build_comparison_outputs(root: Path) -> list[dict[str, object]]:
    root.mkdir(parents=True, exist_ok=True)
    rows: list[dict[str, object]] = []
    for (dataset, attack, method), (acc, asr, ra) in FREQ_PRET_RESULTS.items():
        rows.append({
            "dataset": dataset, "attack": attack, "method": method,
            "acc": acc, "asr": asr, "ra": ra,
            "source": "Zhang et al., IEEE IoT Journal 2026, Table III",
            "status": "published",
        })
    for path in sorted(root.glob("*/*/final_test_summary.json")):
        summary = json.loads(path.read_text(encoding="utf-8"))
        if summary.get("status") != "complete":
            continue
        dataset, attack = summary["dataset"], summary["attack"]
        for key, method in (
            ("no_defense", "Our suspicious model: no defense"),
            ("reference_free_defense", "Our reference-free generator"),
        ):
            values = summary[key]
            rows.append({
                "dataset": dataset, "attack": attack, "method": method,
                "acc": values["clean_accuracy"], "asr": values["asr"],
                "ra": values["robust_accuracy"], "source": str(path),
                "status": "measured",
            })

    with (root / "paper_comparison_table.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader(); writer.writerows(rows)
    (root / "paper_comparison_table.md").write_text(render_markdown(rows), encoding="utf-8")
    return rows


def render_markdown(rows: list[dict[str, object]]) -> str:
    lines = [
        "# CIFAR-100 and Tiny ImageNet comparison", "",
        "Lower ASR is better. Higher ACC and RA are better. ACC is clean-image "
        "accuracy; ASR is the triggered target rate; RA is true-label accuracy on "
        "triggered images.", "",
        "| Dataset | Attack | Method | ACC | ASR | RA |", "|---|---|---|---:|---:|---:|",
    ]
    for row in sorted(rows, key=lambda item: (item["dataset"], item["attack"], item["method"])):
        lines.append(
            f"| {row['dataset']} | {row['attack']} | {row['method']} | "
            f"{100*float(row['acc']):.2f}% | {100*float(row['asr']):.2f}% | "
            f"{100*float(row['ra']):.2f}% |"
        )
    lines.extend([
        "", "## How to use this table", "",
        "Compare only rows with the same dataset and attack family. The Freq-Pret "
        "values are published reference values, while our values are generated by "
        "this repository. They are protocol-aligned, not guaranteed exact reproductions: "
        "pretraining, training budget, trigger carrier, implementation, and data split "
        "may differ. Therefore, describe a numerical advantage as an experimental result "
        "under our stated protocol, not proof that one method is universally superior.", "",
        "ISSBA is retained as a published reference row but is not generated by this "
        "benchmark. An exact ISSBA comparison requires the official sample-specific "
        "encoder/checkpoint; substituting a homemade trigger would be scientifically "
        "misleading. FTrojan rows are additional tests and have no Freq-Pret row in the "
        "cited table.", "",
        "**Published source:** Ping Zhang, Hongyuan Yue, and Chau Yuen, "
        "'Backdoor Defense Strategy for Image Classification Tasks Based on Frequency "
        "Domain Perturbation,' IEEE Internet of Things Journal, 2026, "
        "DOI: 10.1109/JIOT.2026.3671197.",
    ])
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output-root", type=Path,
        default=Path("Benchmark_Outputs/cifar_tiny_reference_free_v4"),
    )
    args = parser.parse_args()
    rows = build_comparison_outputs(args.output_root)
    print(f"Saved {len(rows)} comparison rows to {args.output_root}")


if __name__ == "__main__":
    main()
